package com.epsilon.agent.run;

/** run を回す呼び出しの終わり方。コマンドは、これを終了コードに直す。 */
public enum Ending {
  /** 全ての反復とジョブを終えた（ジョブだけを回す呼び出しでは、待っているジョブを全て終えた）。 */
  FINISHED,
  /** この呼び出しで閉じる反復の数が上限に達した。 */
  LIMIT,
  /** 停止の要求か停止のシグナルを受けて、セーフポイントで止まった。 */
  STOPPED,
  /** 起動し直しの要求を受けて、セーフポイントで止まった。 */
  RESTART,
  /** GPU を譲るために、セーフポイントで止まった。 */
  YIELD,
  /** 設定の行・state・固定した jar のどれかが、この JVM で続けることを許さない。 */
  REFUSED
}
