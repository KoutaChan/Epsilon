package com.epsilon.prism.collect;

/**
 * 収集する経路（{@link CollectionPath}）の種類。
 *
 * <ul>
 *   <li>{@link #MAIN}: 半荘の主経路。全席が b で最後まで打ち、逸脱しない。ラベル行（クラスと手の形ごとの率 ρ）と中立ロールイン（クラスごとの
 *       率 β）を行う。
 *   <li>{@link #COPY}: 主経路の判断から作った写し。逸脱した席 i が d を打ち、以後は全席が b で局末まで打って止まる。ラベル行になるのは席 i の
 *       後の判断だけで、写しの根の判断のクラスで決まる {@link RollInRule} に従い、その判断のクラスの率 ρ_br と写しごとの上限で決める。
 *       ほかの席の行は書かない。入れ子のロールインはしない。
 *   <li>{@link #FORK}: ラベル行の候補 a を測る分岐（主経路か写しから作る）。その席が a を打ち、以後は全席が b で局末まで打って止まる。行を
 *       書かず、さらに分岐もしない。
 * </ul>
 */
public enum Role {
  MAIN,
  COPY,
  FORK
}
