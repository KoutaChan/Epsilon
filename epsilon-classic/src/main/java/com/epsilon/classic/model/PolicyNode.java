package com.epsilon.classic.model;

/**
 * 方策のグラフのノード。Nano では、定数の番号（ordinal）をそのままノードの埋め込みの行に使う。変換した重みはこの名前と並びに
 * 合わせてあるので、どちらも変えない。
 *
 * <p>応答の判断は、ロンか見送るか → 見送るなら鳴くか見送るか → 鳴きの種類 → 種類の中の候補、の順に分かれる。手番の判断は、ツモ和了か
 * 続けるか → 九種九牌か続けるか → 槓か打牌か、の順に分かれる。槓なら種類と候補へ進み、打牌なら物理の打牌 → ダマか立直か、へ進む。
 */
public enum PolicyNode {
  /** ロンか見送るか。 */
  RON_GATE,
  /** ツモ和了か続けるか。 */
  TSUMO_GATE,
  /** 九種九牌か続けるか。 */
  KYUSHU_GATE,
  /** 見送るか鳴くか。 */
  CALL_GATE,
  /** 鳴くときに、チー・ポン・大明槓のどれにするか。 */
  MELD_TYPE,
  /** 同じ種類の鳴きの候補のどれにするか。 */
  MELD_CANDIDATE,
  /** 打牌か槓か。 */
  KAN_GATE,
  /** 槓をするときに、暗槓か加槓か。 */
  KAN_TYPE,
  /** どの物理の打牌にするか。 */
  DISCARD_IDENTITY,
  /** 同じ物理の打牌を、ダマで切るか立直するか。 */
  RIICHI_GATE
}
