/**
 * 運の精算。真の牌山の偶然のイベントを制御変量にして、ラベルのノイズを偏りなく減らす。
 *
 * <p>ラベルの値の受け取り先（分岐の候補か、打った手の主経路）ごとに、判断の後から局末までに起きた偶然のイベントの増分 δ を、受け取り先の
 * 席から見た向きで帳簿の列（{@link LedgerColumn}）に足す。どの増分も、全ての情報が見える状態でイベントの直前までに明らかになったこと
 * （全ての席の手・河・副露・公開済みの表示牌・全ての手と乱数の結果、ネットワークの出力 s と行動の分布 b）を条件として平均 0 なので、
 * 帳簿の期待値は判断の時点で 0 になる。
 *
 * <ul>
 *   <li>ツモ（山・嶺上・抜きの補充、誰のツモでも）: δ = c(x, d) − Σ_t n_t·c(x, t) / N。n_t は誰にも見えない枚数（イベントの前の
 *       プール）、x はツモの前の状態、d は引いた種類。牌山は一様な並べ替えで、開く位置（席別ツモ列を含む）は開いた履歴とも牌山とも独立な乱数
 *       だけで決まるので、引く牌はプールの中で一様に分布する。
 *   <li>槓ドラの表示: 同じ形（表示牌の種類について、表示の前のプール）。
 *   <li>局末の裏ドラ（立直の和了があるときだけ）: 各表示牌の位置にある牌は周辺分布が一様なので、実際の値 − 表示牌の枚数 × プールでの平均。
 *   <li>方策の偶然（判断の後の強制でない判断）: δ = s̄_A − Σ_a b(a)·s̄_a。b は卓が手の抽選に実際に渡した分布で、s̄ は s を上下の幅で
 *       切ったもの。手の抽選の乱数は判断ごとに新しいキーから引くので、牌山とも過去の乱数とも独立。
 * </ul>
 *
 * <p>平均 0 の条件: c はイベントの前に明らかなことだけの関数にする。牌山の中身・開く前の表示牌・裏ドラの表示牌は読まない（採点は裏ドラを
 * 数えない。裏ドラは局末の実際の値にだけ使う）。判断の時点の状態はツモの後なので、ツモった席の手は引いた牌を外して読む。c は牌の種類だけの
 * 関数で、引いた牌が赤かは使わない。最後の判断の時点より後に起き、そのまま局が終わるイベント（荒牌の前の後めくりの表示牌）は数えない。
 * 起きるかどうかが牌に依らないので、平均 0 は保たれる。
 *
 * <p>行に書くときは偏りのない確率的丸めで fp16 にする（{@link LedgerRounding}）。丸めの乱数も牌山と独立。帳簿の計算が有限でない値を
 * 出したら例外にする（行の NaN は「帳簿を付けなかった」ことだけを意味する）。
 */
