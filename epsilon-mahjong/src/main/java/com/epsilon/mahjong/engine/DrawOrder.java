package com.epsilon.mahjong.engine;

/**
 * 局のツモの順。どちらの順でも、引く位置はそれまでのイベントだけで決まり、まだ見えていない牌の中身には依らない。そのため半荘の結果の
 * 分布はどちらも同じになる。違うのは、同じ牌山の半荘どうしがどこまで同じ牌を引くかだけ。
 */
public enum DrawOrder {
  /**
   * 席ごとのツモ列。配牌の後の山を席ごとの列に分け、ツモ・嶺上・北抜きの補充では自分の列の次の牌を引く。鳴き・槓・北抜きで手番が
   * ずれても、列が残っている間は、各席が引く牌の並びは変わらない。
   */
  SEAT_STREAMS,
  /** 牌山の位置の順。ツモは手番に依らず山の次の位置、嶺上・北抜きの補充は王牌の決まった位置を引く。 */
  WALL_ORDER
}
