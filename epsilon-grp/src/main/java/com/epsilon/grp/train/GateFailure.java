package com.epsilon.grp.train;

/** 関門で落ちた理由。報告では宣言の順に並べる。 */
public enum GateFailure {
  /** 候補の Φ、周辺確率、同時確率の対数、単調性の検査の値のどれかに、有限でない値がある。 */
  NOT_FINITE,
  /** 再学習の候補が使用中のモデルより悪く、対応のある MSE の差が +2 SE を超える。 */
  WORSE,
  /** 入れ替えの候補が使用中のモデルより、対応のある MSE の差で 2 SE を超えるほどには良くなっていない。 */
  NOT_BETTER,
  /**
   * 切り替えの後の監視でモデルを戻してから 8 反復の間に出た候補が、戻したモデルより悪く、対応のある MSE の差が +1 SE を
   * 超える。
   */
  WORSE_THAN_ANCHOR,
  /** 点を動かしたときに Φ が逆向きに動く率が、しきい値 max(1.5 × 使用中のモデルの率, 0.005) を超える。 */
  NOT_MONOTONE
}
