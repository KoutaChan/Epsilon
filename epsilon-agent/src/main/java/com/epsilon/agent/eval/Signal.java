package com.epsilon.agent.eval;

/** リグレッションのアラートの種類。 */
public enum Signal {
  /** 王者との決闘で「悪い」が出た。 */
  CHAMPION_WORSE,
  /** 王者との決闘で「悪い」が、決めた回数以上続いている。続く間は決闘ごとに出す。 */
  WORSE_STREAK,
  /** ラダーの卓で、固定の水準の区間の上端が 0 より小さい。 */
  LADDER_WORSE,
  /** 基準の卓の値が王者の基準の卓の値より幅以上悪く、同じ牌山どうしの差の z がしきい値を超える。同じ王者の間は 1 回だけ出す。 */
  BASELINE_DROP,
  /** ルールベースの打ち手との卓の値が王者の同じ卓の値より悪く、同じ牌山どうしの差の z がしきい値を超える。同じ王者の間は 1 回だけ出す。 */
  ANCHOR_DROP
}
