package com.epsilon.agent.eval;

/** 1 つの牌山を何半荘、どの席の割り当てで打つか（{@link ArenaPlan}）。 */
public enum Seating {
  /**
   * 牌山ごとに 1 半荘。分け方はスロット 0 が 1 席のもの 1 つだけで、割り当ての番号は牌山の番号を席の数で割った余り（スロット 0 をその余りの
   * 席に置く）。
   */
  BY_GAME,
  /** 牌山ごとに、全ての分け方の全ての割り当てを 1 半荘ずつ打つ。半荘は分け方の順で、分け方の中は割り当ての番号の順。 */
  EVERY_PLACEMENT
}
